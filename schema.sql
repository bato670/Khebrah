create extension if not exists pgcrypto;

do $$ begin
  create type public.app_role as enum ('user','admin','content_manager','training_manager','services_manager','instructor');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.app_role not null default 'user',
  phone text,
  specialty text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  category text not null default 'عام',
  type text not null default 'برنامج تدريبي',
  description text,
  hours integer not null default 1 check (hours > 0),
  sessions integer not null default 1 check (sessions > 0),
  mode text not null default 'حضوري',
  start_at timestamptz,
  end_at timestamptz,
  price numeric(10,2) not null default 0 check (price >= 0),
  status text not null default 'draft' check (status in ('draft','published','closed')),
  cover_url text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  progress integer not null default 0 check (progress between 0 and 100),
  status text not null default 'enrolled' check (status in ('pending','enrolled','completed','cancelled')),
  enrolled_at timestamptz not null default now(),
  unique(user_id, course_id)
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  course_id bigint references public.courses(id) on delete set null,
  certificate_number text not null unique,
  issued_at timestamptz not null default now(),
  pdf_url text,
  verification_hash text
);

create table if not exists public.experts (
  id bigint generated by default as identity primary key,
  full_name text not null,
  title text,
  bio text,
  specialties text[] not null default '{}',
  avatar_url text,
  is_published boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.content_items (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  content_type text not null default 'article' check (content_type in ('article','research','guide','news','release')),
  excerpt text,
  body text,
  status text not null default 'draft' check (status in ('draft','published')),
  author_id uuid references public.profiles(id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_type text not null default 'فعالية',
  description text,
  starts_at timestamptz,
  ends_at timestamptz,
  location text,
  registration_url text,
  status text not null default 'draft' check (status in ('draft','published','closed')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  service_type text not null,
  subject text not null,
  details text,
  status text not null default 'new' check (status in ('new','reviewing','in_progress','completed','rejected')),
  assigned_to uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  title text not null,
  body text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  entity_type text not null check (entity_type in ('course','content')),
  entity_id bigint not null,
  created_at timestamptz not null default now(),
  primary key(user_id, entity_type, entity_id)
);

create index if not exists idx_courses_status_start on public.courses(status,start_at);
create index if not exists idx_content_status_published on public.content_items(status,published_at);
create index if not exists idx_events_status_start on public.events(status,starts_at);
